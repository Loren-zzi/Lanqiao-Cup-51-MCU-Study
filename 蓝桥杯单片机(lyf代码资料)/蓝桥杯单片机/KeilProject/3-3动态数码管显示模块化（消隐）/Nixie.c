#include <STC15F2K60S2.H>
#include "Delay.h"

unsigned char Segment_Selection[]={0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07,0x7F,0x6F,0x80};
unsigned char Bit_Selection[]={0xFE,0xFD,0xFB,0xF7,0xEF,0xDF,0xBF,0x7F};

void Nixie(unsigned char Bit,Seg)
{
	Bit--;
	P2&=0x1f;
	P2|=0xc0;
	P0=~Bit_Selection[Bit];  
	P2&=0x1f;
	P0=0x00;      //消隐
	P2&=0x1f;
	P2|=0xe0;
	P0=~Segment_Selection[Seg];  
	P2&=0x1f;
	Delay(1);
//P0=0x00;      //消隐
}